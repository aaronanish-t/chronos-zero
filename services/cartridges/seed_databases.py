"""Deterministic seeder for the three cartridge databases (PostgreSQL 16).

Run: python services/cartridges/seed_databases.py   (or `make seed`)
Drops and recreates every cartridge's tables in {CHRONOS_PG_DSN}/chronos_{cartridge_id.lower()}.
The databases themselves come from infra/postgres/init.sql.
"""
import os
import sys
import time

import psycopg

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)
from services.runtime_config import load_config

PG_DSN = load_config().pg_dsn.rstrip("/")

USER_COUNT = 15_420
ROLES = ("viewer", "editor", "admin")

# DOUBLE PRECISION, not REAL: Postgres REAL is float4 and would round values the Z3 verifier compares.
HEALTHCARE_SQL = """
    DROP TABLE IF EXISTS prescriptions, encounters, patients CASCADE;
    CREATE TABLE patients(patient_id TEXT PRIMARY KEY, name TEXT, egfr_ml_min DOUBLE PRECISION, active_meds TEXT);
    CREATE TABLE encounters(encounter_id TEXT, patient_id TEXT, therapy_type TEXT, duration_weeks INTEGER);
    CREATE TABLE prescriptions(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, patient_id TEXT,
                               drug_name TEXT, daily_dose_mg INTEGER, claim_submitted INTEGER,
                               conservative_therapy_weeks INTEGER);
    INSERT INTO patients VALUES ('pat_402', 'John Doe', 24.0, 'Lisinopril');
    INSERT INTO encounters VALUES ('enc_108', 'pat_402', 'Physical Therapy', 6);
"""

FINTECH_SQL = """
    DROP TABLE IF EXISTS transfers, vendors, treasury CASCADE;
    CREATE TABLE treasury(account_id TEXT PRIMARY KEY, balance_usd DOUBLE PRECISION,
                          daily_spent_usd DOUBLE PRECISION, daily_limit_usd DOUBLE PRECISION);
    CREATE TABLE vendors(vendor_id TEXT PRIMARY KEY, name TEXT, iban TEXT, allowlisted INTEGER,
                         sla_latency_ms DOUBLE PRECISION);
    CREATE TABLE transfers(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, vendor_id TEXT,
                           amount_usd DOUBLE PRECISION, status TEXT);
    INSERT INTO treasury VALUES ('acct_treasury', 50000.0, 4200.0, 5000.0);
    INSERT INTO vendors VALUES ('vnd_spoof', 'Acme Logistics (spoofed)', 'GB82WEST12345698765432', 0, 640.0),
                               ('vnd_verified', 'Acme Logistics', 'DE89370400440532013000', 1, 85.0);
"""

DEVOPS_SQL = """
    DROP TABLE IF EXISTS users, security_groups CASCADE;
    CREATE TABLE users(id INTEGER PRIMARY KEY, email TEXT, role TEXT);
    CREATE TABLE security_groups(sg_id TEXT PRIMARY KEY, port INTEGER, cidr_open_world INTEGER);
    INSERT INTO security_groups VALUES ('sg_prod', 443, 0);
"""


def db_dsn(cartridge_id: str) -> str:
    return f"{PG_DSN}/chronos_{cartridge_id.lower()}"


def seed_devops(cur: psycopg.Cursor) -> None:
    cur.execute(DEVOPS_SQL)
    with cur.copy("COPY users (id, email, role) FROM STDIN") as copy:
        for i in range(1, USER_COUNT + 1):
            copy.write_row((i, f"user{i:05d}@example.com", ROLES[i % 3]))


SEEDERS = {
    "HEALTHCARE_FHIR": lambda cur: cur.execute(HEALTHCARE_SQL),
    "FINTECH_ESCROW": lambda cur: cur.execute(FINTECH_SQL),
    "CLOUD_DEVOPS": seed_devops,
}


def seed_all() -> float:
    """Reset every cartridge DB, one transaction each; returns elapsed milliseconds."""
    t0 = time.perf_counter_ns()
    for cartridge_id, seed in SEEDERS.items():
        with psycopg.connect(db_dsn(cartridge_id), connect_timeout=3) as conn, conn.cursor() as cur:
            seed(cur)
    return (time.perf_counter_ns() - t0) / 1_000_000.0


if __name__ == "__main__":
    try:
        ms = seed_all()
    except psycopg.Error as exc:
        sys.exit(f"seed failed (is Postgres up and init.sql applied? CHRONOS_PG_DSN={PG_DSN.split('@')[-1]}): {exc}")
    print(f"Seeded {len(SEEDERS)} cartridge DBs on {PG_DSN.split('@')[-1]} in {ms:.1f} ms")
